'use strict';
const {chromium}=require('C:/Users/asus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
  const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:4188/',{waitUntil:'networkidle'});
    await page.waitForSelector('#ticker .ticker-price-line',{state:'attached'});
    const ticker=page.locator('#ticker');
    await ticker.hover();
    await page.waitForFunction(()=>getComputedStyle(document.querySelector('.ticker-detail')).opacity==='1');
    const first=await ticker.locator('.ticker-entry').innerText();
    assert.ok(!first.includes('AWS'));
    const curve=await ticker.locator('.ticker-price-line').getAttribute('d');
    assert.ok(curve.includes('L'));
    await page.waitForTimeout(4700);
    assert.equal(await ticker.locator('.ticker-entry').innerText(),first,'hover must pause rotation');
    await page.screenshot({path:path.resolve('.opennext-data/home-ticker-desktop.png')});
    await page.mouse.move(10,900);
    await page.waitForFunction(previous=>document.querySelector('#ticker .ticker-entry').innerText!==previous,first,{timeout:6500});
    const changed=await ticker.locator('.ticker-entry').innerText();
    assert.notEqual(first,changed);
    await ticker.focus();
    const focused=await ticker.locator('.ticker-entry').innerText();
    await page.waitForTimeout(4700);
    assert.equal(await ticker.locator('.ticker-entry').innerText(),focused,'keyboard focus must pause rotation');
    await page.evaluate(()=>document.activeElement.blur());
    await page.waitForFunction(previous=>document.querySelector('#ticker .ticker-entry').innerText!==previous,focused,{timeout:6500});
    await ticker.locator('.ticker-control').click();
    await page.mouse.move(10,900);
    await page.evaluate(()=>document.activeElement.blur());
    const paused=await ticker.locator('.ticker-entry').innerText();
    await page.waitForTimeout(4700);
    assert.equal(await ticker.locator('.ticker-entry').innerText(),paused,'manual pause must persist');
    assert.equal(await page.locator('.on-listing-card-top .on-listing-sample').count(),0);
    assert.ok((await page.locator('.on-listing-urgency').allTextContents()).every(t=>t==='High Urgency'));
    assert.equal(await page.locator('.public-vision-band .public-capability-status').first().innerText(),'Live');
    await page.setViewportSize({width:390,height:844});
    await ticker.hover();
    await page.waitForFunction(()=>getComputedStyle(document.querySelector('.ticker-detail')).opacity==='1');
    const bounds=await page.locator('.ticker-detail').boundingBox();
    assert.ok(bounds.x>=0&&bounds.x+bounds.width<=390,'mobile tooltip must fit viewport');
    await page.screenshot({path:path.resolve('.opennext-data/home-ticker-mobile.png')});
    assert.deepEqual(errors,[]);
    console.log('PASS: history curve, hover/resume/manual pause, homepage badges, Live label and mobile bounds.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
