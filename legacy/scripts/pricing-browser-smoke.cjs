'use strict';
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{}),headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.TEST_BASE||'http://127.0.0.1:4190';
 await page.goto(base,{waitUntil:'networkidle'});
 assert.match(await page.title(),/OpenNEXT/);
 await page.evaluate(()=>{Object.assign(window.ONPreview.state,{auth:true,model:'H100',region:'All regions',term:'On-demand',count:8});window.ONPreview.navigate('market');});
 await page.waitForFunction(()=>document.querySelectorAll('.chart-series').length>0||document.body.innerText.includes('AWS'));
 await page.waitForTimeout(1200);
 await page.screenshot({path:path.resolve('.opennext-data/terminal-test.png'),fullPage:true});
 console.log('Terminal:',(await page.locator('main').innerText()).slice(0,2100));
 const before=await page.locator('main').innerText();
 await page.locator('[data-act="filter"][data-type="model"]').click();
 await page.locator('#modelSearch').fill('B200');
 await page.locator('[data-act="select-filter"][data-value="B200"]').click();
 await page.waitForTimeout(600);
 assert.match(await page.locator('main').innerText(),/B200/);
 assert.notEqual(before,await page.locator('main').innerText());
 const detail=page.locator('[data-act="detail"]').first();await detail.click();
 console.log('Detail:',(await page.locator('#overlays').innerText()).slice(0,550));
 await page.keyboard.press('Escape');
 await page.locator('[data-act="filter"][data-type="term"]').click();
 await page.locator('[data-act="select-filter"][data-value="Spot"]').click();
 await page.waitForTimeout(500);assert.match(await page.locator('main').innerText(),/AWS|Spot/);
 assert.doesNotMatch(await page.locator('main').innerText(),/NaN|undefined|Invalid Date/);
 await page.goto(base+'/admin/#pricing',{waitUntil:'networkidle'});
 await page.waitForSelector('.pc-card');assert.equal(await page.locator('.pc-card').count(),24);
 await page.screenshot({path:path.resolve('.opennext-data/console-test.png'),fullPage:true});
 await page.locator('[data-pc-search]').fill('AWS');assert.equal(await page.locator('.pc-card').count(),1);
 await page.locator('[data-pc="detail"][data-provider="aws"]').first().click();
 await page.waitForSelector('dialog[open]');assert.match(await page.locator('dialog').innerText(),/AWS/);
 await page.locator('dialog [data-pc="prices"]').click();
 await page.waitForTimeout(300);assert.ok(await page.locator('dialog tbody tr').count()>1);
 await page.locator('dialog [data-pc="close"]').click();
 await page.locator('[data-pc-search]').fill('');
 await page.locator('[data-pc="job"]').first().click();await page.waitForSelector('dialog[open]');
 console.log('Log:',(await page.locator('dialog').innerText()).slice(0,550));
 await page.keyboard.press('Escape');
 await page.locator('[data-pc-search]').fill('Vultr');
 await page.locator('[data-pc="detail"][data-provider="vultr"]').first().click();
 await page.locator('dialog input[name="intervalMinutes"]').fill('60');
 await page.locator('dialog button', {hasText:'Save settings'}).click();
 await page.waitForFunction(()=>!document.querySelector('dialog[open]'));
 await page.locator('[data-pc="run"][data-provider="vultr"]').click();
 await page.waitForSelector('dialog[open]');
 const activeRunId=await page.locator('dialog [data-pc="job"]').getAttribute('data-run');
 let completedRun;
 for(let attempt=0;attempt<50;attempt++){completedRun=await(await page.request.get(base+'/api/admin/pricing/runs/'+activeRunId)).json();if(completedRun.id===activeRunId&&completedRun.status!=='running')break;await page.waitForTimeout(400);}
 assert.notEqual(completedRun.status,'running');
 await page.locator('dialog [data-pc="job"]').click();
 await page.waitForTimeout(500);
 console.log('Manual run log',await page.locator('dialog').innerText());
 assert.match(await page.locator('dialog').innerText(),/completed|failed/i);
 await page.keyboard.press('Escape');
 await page.locator('[data-pc-search]').fill('');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.resolve('.opennext-data/console-mobile.png'),fullPage:true});
 console.log('Mobile width',await page.evaluate(()=>({body:document.body.scrollWidth,viewport:innerWidth})));
 assert.deepEqual(errors,[]);console.log('Browser smoke passed');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
