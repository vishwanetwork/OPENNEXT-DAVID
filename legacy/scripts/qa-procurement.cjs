'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require(process.env.OPENNEXT_PLAYWRIGHT_PATH || 'C:/Users/asus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const out = path.resolve(__dirname, '../.opennext-data');
fs.mkdirSync(out, { recursive: true });
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.OPENNEXT_CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const act=(name,where=page)=>where.locator('[data-act="'+name+'"]').first();
  const modal=()=>page.locator('.modal');
  const state=()=>page.evaluate(()=>JSON.parse(JSON.stringify(window.ONPreview.state)));
  try {
    await page.goto(process.env.OPENNEXT_BASE_URL || 'http://127.0.0.1:4188/', {waitUntil:'domcontentloaded'});
    await page.waitForFunction(()=>!!window.ONPreview);
    await page.evaluate(()=>{const s=window.ONPreview.state;s.auth=true;s.role='Buyer';window.ONPreview.navigate('market');});
    await page.getByRole('heading',{name:'Best Matches',exact:true}).waitFor();
    assert.equal((await state()).balance,0);
    assert.equal(await page.locator('.proc-match-viewport').count(),2);
    assert.equal(await page.locator('.proc-match-viewport').first().locator('.match-cycle .proc-match').count(),5);
    assert.equal(await page.locator('.market-tabs').getByRole('button').count(),1);
    await act('refresh-matches').click();
    await page.screenshot({path:path.join(out,'procurement-market-desktop.png'),fullPage:true});
    await act('new-rfq').click();
    const form=page.locator('form[data-form="proc-rfq"]');
    await form.locator('[name=title]').fill('QA inference workload');
    await form.locator('[name=project]').fill('Research cost centre');
    await form.locator('[name=count]').fill('1');
    await form.locator('[name=hours]').fill('2');
    await form.locator('[name=budget]').fill('3');
    await form.locator('[name=notes]').fill('1 H100 GPU, CUDA 12, model inference. Verify access and memory before acceptance.');
    await form.getByRole('button',{name:'Post RFQ',exact:true}).click();
    await act('proc-sample-quotes').click();
    assert.equal(await page.locator('.proc-quote').count(),3);
    await act('proc-reject').click();
    assert.equal(await page.locator('.proc-quote').count(),2);
    await page.screenshot({path:path.join(out,'procurement-competing-quotes.png'),fullPage:true});
    await act('proc-accept-review').click();
    await act('proc-accept-confirm').click();
    let s=await state(),order=s.orders[0];
    assert.equal(order.status,'Awaiting payment');
    assert.equal(s.notifications.filter(n=>n.subject==='RFQ closed').length,1);
    await act('proc-payment').click();
    await act('pay-start').click();
    await page.locator('form[data-form="pay-amount"]').getByRole('button',{name:'Continue to checkout'}).click();
    await act('pay-confirm').click();
    assert.equal((await state()).balance,100);
    await act('bill-order').click();
    await act('proc-payment').click();
    await act('proc-pay-confirm').click();
    s=await state();assert.equal(s.balance,100-order.total);assert.equal(s.orders[0].paymentStatus,'Paid');
    await act('proc-delivery').click();
    await page.locator('form[data-form="proc-delivery"] [name=access]').fill('ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIExamplePreviewPublicKeyOnly buyer@example.test');
    await page.locator('form[data-form="proc-delivery"] input[type=checkbox]').check();
    await page.locator('form[data-form="proc-delivery"] button[type=submit],form[data-form="proc-delivery"] button:not([type])').click();
    await act('proc-verify').click();
    for(const checkbox of await page.locator('form[data-form="proc-verify"] input[type=checkbox]').all())await checkbox.check();
    await page.locator('form[data-form="proc-verify"]').getByRole('button',{name:'Accept test delivery'}).click();
    assert.equal((await state()).orders[0].status,'Active');
    await act('proc-manage').click();await act('proc-complete').click();
    assert.equal((await state()).orders[0].status,'Completed');
    await page.evaluate(()=>window.ONPreview.navigate('billing'));
    await page.locator('[data-act="bill-order"][data-id="'+order.id+'"]').first().click();
    await page.screenshot({path:path.join(out,'procurement-order-details.png'),fullPage:true});
    assert.match(await modal().innerText(),/Payment confirmed|payment confirmed/);
    await act('close-modal',modal()).click();
    await page.evaluate(()=>{const s=window.ONPreview.state;s.role='Seller';s.review={status:'Approved',step:4,company:'Nova Compute'};window.ONPreview.navigate('market');});
    await page.locator('.matches').first().locator('[data-act=proc-opportunity]').first().click();
    let responseForm=page.locator('form[data-form="proc-response"]');
    await responseForm.locator('[name=evidence]').fill('capacity-test-preview-001');
    await responseForm.locator('[name=specification]').fill('H100, InfiniBand, 1 TB NVMe');
    await responseForm.locator('[name=notes]').fill('99.9% SLA, SSH delivery after payment; cancellation before provisioning.');
    await responseForm.getByRole('button',{name:'Submit capacity for verification'}).click();
    await act('proc-response-test').click();await act('proc-response-accept').click();await act('bill-order',modal()).click();
    for(let i=0;i<4;i++)await act('proc-seller-progress').click();
    s=await state();const sellOrder=s.orders.find(o=>o.side==='sell');
    assert.equal(sellOrder.status,'Completed');assert.equal(s.earningsBalance,sellOrder.total);
    assert.equal(s.ledger.filter(e=>e.orderId===sellOrder.id&&e.type==='Sale settlement').length,1);
    await page.screenshot({path:path.join(out,'procurement-seller-settlement.png'),fullPage:true});
    await act('close-modal',modal()).click();
    await page.evaluate(()=>{window.ONPreview.state.role='Broker';window.ONPreview.navigate('billing');});
    assert.equal(await page.locator('.sidebar [data-nav=supply]').count(),1);
    assert.equal(await page.locator('.sidebar [data-nav=mandates]').count(),1);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'procurement-broker-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ok:true,buyerOrder:order.id,sellerOrder:sellOrder.id,errors,screenshots:out}));
  } catch(error) {
    await page.screenshot({path:path.join(out,'procurement-qa-error.png'),fullPage:true});
    console.error('QA state',JSON.stringify({url:page.url(),toast:await page.locator('#toast').textContent().catch(()=>''),modal:await modal().innerText().catch(()=>''),errors}));
    throw error;
  } finally {await browser.close();}
}
main().catch(e=>{console.error(e);process.exitCode=1;});
