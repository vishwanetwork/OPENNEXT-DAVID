/** Capability ports only. Cashout has no production API adapter until the backend contract exists. */
export type CashoutStatus = 'pending' | 'completed' | 'failed';

export interface CashoutBankDetails {
  beneficiaryName: string;
  beneficiaryAddress: string;
  bankName: string;
  bankCountry: string;
  bankAddress: string;
  accountNumber: string;
  iban: string;
  swiftBic: string;
  routingCode: string;
  intermediaryBank: string;
  intermediarySwiftBic: string;
}

/** List responses contain masked banking details only; full details require a separate read. */
export interface CashoutRecord {
  id: string;
  accountId: string;
  accountNumber: string;
  email: string;
  amountCents: number;
  currency: 'USD';
  status: CashoutStatus;
  revision: number;
  kybId: string;
  kybRevision: number;
  companyName: string;
  registrationNumber: string;
  companyCountry: string;
  bankName: string;
  bankCountry: string;
  maskedAccount: string;
  submittedAt: string;
  completedAt?: string;
  transferReference?: string;
  idempotencyKey: string;
}

export interface CashoutSnapshot {
  confirmed: boolean;
  accountId: string;
  demo: false;
  currency: 'USD';
  balanceRevision: number;
  /** Server ledger excludes promotional, held, unsettled and already reserved amounts. */
  withdrawableCents: number;
  kybId: string;
  kybRevision: number;
  /** Durable server-issued submission key; never regenerated by the browser after a timeout. */
  submissionKey: string;
  requests: CashoutRecord[];
}

export interface CashoutSubmission {
  accountId: string;
  amountCents: number;
  currency: 'USD';
  expectedBalanceRevision: number;
  kybId: string;
  expectedKybRevision: number;
  companyName: string;
  registrationNumber: string;
  companyCountry: string;
  bank: CashoutBankDetails;
  idempotencyKey: string;
}

export interface CashoutSubmissionReceipt {
  confirmed: boolean;
  accountId: string;
  idempotencyKey: string;
  reservedAmountCents: number;
  balanceRevision: number;
  request: CashoutRecord;
}

export interface CashoutService {
  load: (signal?: AbortSignal) => Promise<CashoutSnapshot>;
  /** Authorize owner, recheck KYB and reserve eligible funds atomically before acknowledgement. */
  submit: (input: CashoutSubmission) => Promise<CashoutSubmissionReceipt>;
}

export interface CashoutAdminDetails {
  confirmed: boolean;
  sessionScope: string;
  requestId: string;
  accountId: string;
  revision: number;
  bank: CashoutBankDetails;
}

export interface CashoutCompletion {
  confirmed: boolean;
  requestId: string;
  accountId: string;
  revision: number;
  status: 'completed';
  amountCents: number;
  currency: 'USD';
  transferReference: string;
  idempotencyKey: string;
  notificationQueued: boolean;
  emailQueued: boolean;
  reservationSettled: boolean;
}

export interface CashoutAdminService {
  readonly sessionScope: string;
  list: (signal?: AbortSignal) => Promise<{
    confirmed: boolean;
    sessionScope: string;
    requests: CashoutRecord[];
  }>;
  details?: (input: {
    requestId: string;
    accountId: string;
    expectedRevision: number;
    signal?: AbortSignal;
  }) => Promise<CashoutAdminDetails>;
  /** Confirmation records a completed bank payout, settles the hold and enqueues both notices. */
  complete?: (input: {
    requestId: string;
    accountId: string;
    expectedRevision: number;
    transferReference: string;
    idempotencyKey: string;
  }) => Promise<CashoutCompletion>;
}
